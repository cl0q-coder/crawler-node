// Package quality holds crawl-time content-quality detectors for Track K
// (crawler-node #284). Parked, soft-404, and near-duplicate junk must be
// flagged before indexing, or the 100M-QUALITY bar is meaningless.
//
// K1 (parked-domain detection): parking pages, registrar landers, and
// "domain for sale" templates are content-free — flag them so the pre-index
// gate can drop them (gate is a separate wire-in PR; Claude has final say on
// anything changing what gets indexed, so this package is a pure detector
// with no crawl-behavior change).
//
// Design rules:
//   - DetectParked is a pure function: no I/O, no DB, no DNS. It runs on the
//     normalized page the crawler already built (title, visible text,
//     structural counts), so it costs one pass over strings.
//   - Every verdict carries auditable reasons ("text:buy-this-domain") and a
//     score in [0,1]. Score + reasons let us MEASURE precision/recall on a
//     labeled sample before any gate acts on the verdict (SafeSearch lesson:
//     never over-filter legit sites).
package quality

import "strings"

// Page is the normalized view of a crawled page that the detectors read.
// All text fields are expected as-is; DetectParked lowercases internally.
type Page struct {
	Domain          string // registrable domain, e.g. "example.com"
	Title           string // <title> text
	Text            string // visible text of the page
	WordCount       int    // visible word count
	OutboundAdLinks int    // <a> links to known ad/tracking hosts
	SingleAdFrame   bool   // page body is effectively one iframe/embed + no real text
}

// Verdict is a detector's answer for one page.
type Verdict struct {
	Parked  bool     // Score >= ParkedThreshold
	Score   float64  // weighted signal strength in [0,1]
	Reasons []string // auditable signal codes, e.g. "text:buy-this-domain"
}

// ParkedThreshold is the score at which a page counts as parked. Tunable,
// not sacred; the labeled-sample measurement (Track K acceptance) sets it.
const ParkedThreshold = 0.60

// parkingPhrases are boilerplate strings from parking services, registrar
// landers, and aftermarket templates. Each hit contributes one text signal.
// All matches are case-insensitive substring checks on title + visible text.
// NOTE: phrases were chosen to avoid common prose — see the noindex/legit
// fixtures in parked_test.go (the SafeSearch lesson: never eat legit sites).
var parkingPhrases = []struct {
	phrase string
	weight float64
	reason string
}{
	{"this domain is for sale", 0.45, "text:this-domain-is-for-sale"},
	{"buy this domain", 0.45, "text:buy-this-domain"},
	{"domain is parked", 0.40, "text:domain-is-parked"},
	{"this domain is parked", 0.40, "text:this-domain-is-parked"},
	{"parked by the owner", 0.40, "text:parked-by-the-owner"},
	{"parked free", 0.25, "text:parked-free"},
	{"for sale by owner", 0.30, "text:for-sale-by-owner"},
	{"make an offer", 0.20, "text:make-an-offer"},
	{"this webpage was generated by the domain owner", 0.40, "text:generated-by-domain-owner"},
	{"related searches", 0.15, "text:related-searches"},
}

// minTextWords is the floor below which a page with ad links looks like a
// parked template rather than a thin-but-real page. Kept high enough that
// legit one-liners ("under construction") don't trip it alone — a text
// phrase must also match (see DetectParked).
const minTextWords = 40

// DetectParked scores a crawled page for parked-domain/template junk.
// It never reads anything but the Page it is given: pure and cheap.
func DetectParked(p Page) Verdict {
	v := Verdict{Score: 0}
	lower := func(s string) string { return strings.ToLower(s) }
	hay := lower(p.Title + "\n" + p.Text)

	for _, pp := range parkingPhrases {
		if strings.Contains(hay, pp.phrase) {
			v.Score += pp.weight
			v.Reasons = append(v.Reasons, pp.reason)
		}
	}

	// Title == "<domain> for sale" — the classic aftermarket lander title.
	d := lower(strings.TrimSpace(p.Domain))
	t := lower(strings.TrimSpace(p.Title))
	if d != "" && (t == d+" for sale" || t == "buy "+d || strings.HasPrefix(t, d+" is for sale")) {
		v.Score += 0.35
		v.Reasons = append(v.Reasons, "title:domain-for-sale")
	}

	// Structural: single ad frame with near-zero text is the parking
	// template shape (one iframe, ad links, nothing else). Weighted so it
	// trips the threshold together with the tiny-text-ad-links signal
	// (0.35 + 0.25 = 0.60) — an ad frame alone is not enough, since legit
	// embed pages share the shape.
	if p.SingleAdFrame && p.WordCount < minTextWords {
		v.Score += 0.35
		v.Reasons = append(v.Reasons, "structural:single-ad-frame")
	}

	// Structural: tiny text + ad-heavy outbound links, no title content.
	if p.WordCount < minTextWords && p.OutboundAdLinks >= 3 {
		v.Score += 0.25
		v.Reasons = append(v.Reasons, "structural:tiny-text-ad-links")
	}

	if v.Score > 1 {
		v.Score = 1
	}
	v.Parked = v.Score >= ParkedThreshold
	return v
}
